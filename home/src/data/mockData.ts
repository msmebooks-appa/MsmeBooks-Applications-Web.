const formatCurrencyWithCode = (
  amtInNGN: number,
  symbol: string,
  rate: number,
  decimals = 0,
  compact = false
): string => {
  const converted = amtInNGN * rate;
  if (compact) {
    if (Math.abs(converted) >= 1_000_000_000) {
      return `${symbol}${(converted / 1_000_000_000).toFixed(1)}B`;
    }
    if (Math.abs(converted) >= 1_000_000) {
      return `${symbol}${(converted / 1_000_000).toFixed(1)}M`;
    }
    if (Math.abs(converted) >= 1_000) {
      return `${symbol}${(converted / 1_000).toFixed(1)}K`;
    }
  }

  // Formatting with spacing if symbol is multi-letter
  const prefix = symbol.length > 1 ? `${symbol} ` : symbol;
  if (decimals === 0 || Math.abs(converted) >= 500) {
    return `${prefix}${Math.round(converted).toLocaleString()}`;
  }
  return `${prefix}${converted.toLocaleString(undefined, {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })}`;
};

