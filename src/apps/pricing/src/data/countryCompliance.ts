export function getComplianceForCountry(countryName: string): CountryComplianceInfo {
  // Normalize match
  const direct = COUNTRY_COMPLIANCE_DATA[countryName];
  if (direct) return direct;

  const lower = countryName.toLowerCase();
  for (const [key, data] of Object.entries(COUNTRY_COMPLIANCE_DATA)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return data;
    }
  }

  // Fallback to Nigeria
  return COUNTRY_COMPLIANCE_DATA.Nigeria;
}
