/**
 * Helper to retrieve all states/cities for a selected country.
 * If no country is specified or "All Countries", returns all unique cities sorted.
 */
export const getCitiesForCountry = (countryName?: string): string[] => {
  if (!countryName || countryName === 'All Countries' || countryName.trim() === '') {
    const citySet = new Set<string>();
    COUNTRIES_LIST.forEach((c) => {
      if (c.cities && Array.isArray(c.cities)) {
        c.cities.forEach((city) => citySet.add(city));
      }
    });
    return Array.from(citySet).sort();
  }

  const normalized = countryName.toLowerCase().trim();
  const found = COUNTRIES_LIST.find(
    (c) => c.name.toLowerCase() === normalized || c.code.toLowerCase() === normalized
  );

  if (found && found.cities && found.cities.length > 0) {
    return found.cities;
  }

  return [];
};
